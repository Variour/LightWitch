#!/usr/bin/env python3
"""
Generates CaBundle.S, a full public root-CA bundle for the ESP32 mbedtls
certificate-bundle verifier. Used by Updater.h to validate TLS certs for the
GitHub API and release asset CDN without pinning to specific roots — this is
a generic public trust store, not something specific to GitHub.

The bundle is emitted under the symbols ESP-IDF's esp_crt_bundle reads its
built-in bundle from (_binary_x509_crt_bundle_start/_end), the same way
ESP-IDF embeds its own x509_crt_bundle. The linker then takes this bundle as
the built-in one (WiFiClientSecure::useBuiltinCACertBundle) and leaves
ESP-IDF's bundle out of the firmware.

Binary format matches the ESP-IDF 5.x esp_crt_bundle parser
(components/mbedtls/esp_crt_bundle/esp_crt_bundle.c):
  [offset of 1st cert](u32, little-endian) ... [offset of nth cert](u32, little-endian)
  [1st cert] ... [nth cert]
  cert = [len(CN)](u16, little-endian) [len(key)](u16, little-endian)
         [CN bytes] [key bytes]
Offsets count from the start of the bundle, so the first offset equals the
size of the offset list. Certs are sorted ascending by CN (DER-encoded
subject) for binary search.

Requires: pip install cryptography certifi
Usage: python3 scripts/gen_ca_bundle.py [src/update/CaBundle.S]
"""
import sys
import struct
import certifi
from cryptography import x509
from cryptography.hazmat.backends import default_backend
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

START_SYMBOL = "_binary_x509_crt_bundle_start"
END_SYMBOL = "_binary_x509_crt_bundle_end"


def load_certs(pem_path):
    with open(pem_path, "rb") as f:
        data = f.read()
    certs = []
    for block in data.split(b"-----BEGIN CERTIFICATE-----"):
        if b"-----END CERTIFICATE-----" not in block:
            continue
        pem = (
            b"-----BEGIN CERTIFICATE-----"
            + block.split(b"-----END CERTIFICATE-----")[0]
            + b"-----END CERTIFICATE-----\n"
        )
        certs.append(x509.load_pem_x509_certificate(pem, default_backend()))
    return certs


def build_bundle(certs):
    entries = []
    for cert in certs:
        cn_der = cert.subject.public_bytes(default_backend())
        key_der = cert.public_key().public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo)
        if len(cn_der) > 0xFFFF or len(key_der) > 0xFFFF:
            continue
        entries.append((cn_der, key_der))

    entries.sort(key=lambda e: e[0])

    n = len(entries)
    offsets = []
    bodies = []
    pos = 4 * n
    for cn_der, key_der in entries:
        body = struct.pack("<HH", len(cn_der), len(key_der)) + cn_der + key_der
        offsets.append(pos)
        bodies.append(body)
        pos += len(body)

    out = struct.pack(f"<{n}I", *offsets) + b"".join(bodies)
    return out, n


def emit_asm(bundle, count, out_path):
    with open(out_path, "w") as f:
        f.write(f"/* Generated by scripts/gen_ca_bundle.py — {count} root CAs, {len(bundle)} bytes.\n")
        f.write(" * Do not edit by hand; re-run the script to refresh the bundle. */\n\n")
        f.write("    .section .rodata.embedded, \"a\"\n")
        f.write("    .balign 4\n")
        f.write(f"    .global {START_SYMBOL}\n")
        f.write(f"{START_SYMBOL}:\n")
        for i in range(0, len(bundle), 16):
            chunk = bundle[i:i + 16]
            f.write("    .byte " + ", ".join(f"0x{b:02x}" for b in chunk) + "\n")
        f.write(f"    .global {END_SYMBOL}\n")
        f.write(f"{END_SYMBOL}:\n")


if __name__ == "__main__":
    pem_path = certifi.where()
    certs = load_certs(pem_path)
    bundle, count = build_bundle(certs)
    print(f"source PEM: {pem_path}", file=sys.stderr)
    print(f"parsed {len(certs)} certs, {count} usable in bundle", file=sys.stderr)
    print(f"bundle size: {len(bundle)} bytes", file=sys.stderr)
    out_path = sys.argv[1] if len(sys.argv) > 1 else "src/update/CaBundle.S"
    emit_asm(bundle, count, out_path)
    print(f"wrote {out_path}", file=sys.stderr)
